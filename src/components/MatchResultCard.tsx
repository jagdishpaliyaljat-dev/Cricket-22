import React, { useRef, forwardRef } from 'react';
import { CricketMatch, Player } from '../types/cricket';
import { Trophy, Award } from 'lucide-react';

interface MatchResultCardProps {
  match: CricketMatch;
  playersMap: Record<string, Player>;
}

export const MatchResultCard = forwardRef<HTMLDivElement, MatchResultCardProps>(({ match, playersMap }, ref) => {
  const allBatters = [
    ...(Object.values(match.innings1?.batters || {})),
    ...(Object.values(match.innings2?.batters || {})),
  ];
  const allBowlers = [
    ...(Object.values(match.innings1?.bowlers || {})),
    ...(Object.values(match.innings2?.bowlers || {})),
  ];

  const topBatter = allBatters.sort((a, b) => b.runs - a.runs)[0];
  const topBowler = allBowlers.sort((a, b) => b.wickets - a.wickets)[0];
  const potm = match.result?.playerOfTheMatchId ? playersMap[match.result.playerOfTheMatchId] : null;

  return (
    <div ref={ref} className="w-[400px] bg-[#1554B8] p-6 text-white space-y-4 rounded-2xl shadow-2xl border border-[#0B3F91]">
      <div className="text-center space-y-1">
        <h2 className="text-2xl font-black text-white">{match.title}</h2>
        <p className="text-sm text-[#EAF2FF]">{match.venue} • {new Date(match.dateTime).toLocaleDateString()}</p>
      </div>

      <div className="bg-[#0B3F91] p-4 rounded-xl text-center border border-white/20">
        <h3 className="text-xl font-bold text-white">{match.result?.summaryText || 'Match Result'}</h3>
      </div>

      <div className="grid grid-cols-3 gap-2 text-center">
        {potm && (
          <div className="bg-[#0B3F91]/80 border border-white/10 p-2.5 rounded-xl">
            <Award className="w-6 h-6 mx-auto text-[#EAF2FF]" />
            <p className="text-[10px] uppercase font-bold text-white/70">POTM</p>
            <p className="text-xs font-bold truncate text-white">{potm.fullName}</p>
          </div>
        )}
        {topBatter && (
          <div className="bg-[#0B3F91]/80 border border-white/10 p-2.5 rounded-xl">
            <p className="text-[10px] uppercase font-bold text-white/70">Top Batter</p>
            <p className="text-xs font-bold truncate text-white">{topBatter.playerName}</p>
            <p className="text-sm font-black text-white">{topBatter.runs} ({topBatter.balls})</p>
          </div>
        )}
        {topBowler && (
          <div className="bg-[#0B3F91]/80 border border-white/10 p-2.5 rounded-xl">
            <p className="text-[10px] uppercase font-bold text-white/70">Top Bowler</p>
            <p className="text-xs font-bold truncate text-white">{topBowler.playerName}</p>
            <p className="text-sm font-black text-white">{topBowler.wickets} / {topBowler.runsConceded}</p>
          </div>
        )}
      </div>
      
      <div className="text-center pt-2 border-t border-white/20">
        <p className="text-xs text-[#EAF2FF]">Generated by LocalXI Cricket</p>
      </div>
    </div>
  );
});
MatchResultCard.displayName = 'MatchResultCard';
